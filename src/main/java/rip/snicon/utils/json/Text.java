package rip.snicon.utils.json;

public class Text {

    private String text;
    private String color;
    private boolean bold;
    private boolean italic;


    public String getText() {
        return text;
    }

    public String getColor() {
        return color;
    }

    public boolean isBold() {
        return bold;
    }

    public boolean isItalic() {
        return italic;
    }
}
